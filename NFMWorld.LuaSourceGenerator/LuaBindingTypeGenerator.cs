    /// <summary>Emits method delegate fields grouped by Lua name, skipping overloads/methods with unmarshallable types.</summary>
    private void EmitBindableMethods(IndentedStringBuilder sb, IEnumerable<LuaMethodMetadata> methods)
    {
        foreach (var group in methods.GroupBy(m => m.LuaName))
        {
            var bindable = group.Where(IsMethodBindable).ToArray();
            if (bindable.Length == 0)
            {
                sb.AppendLine($"#warning {type.TypeName}.{group.Key} skipped: no bindable overloads (unsupported parameter or return type)");
                continue;
            }
            EmitMethod(sb, bindable);
        }
    }

    // (Generated runtime helpers are emitted once in _init.cs.)

    private void EmitMethod(IndentedStringBuilder sb, IReadOnlyList<LuaMethodMetadata> overloads)
    {
        // Stable sort by OverloadPriority — ties keep collection (declaration) order,
        // which is the fallback order overload resolution tries candidates in.
        overloads = [.. overloads.OrderBy(m => m.OverloadPriority)];

        var baseMethod = overloads[0];

        var argOffset = baseMethod.IsStatic || baseMethod.IsInstanceConstructor ? 0 : 1;
        sb.AppendLine($"internal static readonly global::NuLua.LuaFunc<global::NuLua.Luau.LuauState> {GetFunctionName(type, baseMethod)} = (state, args) =>");
        using (sb.Block(end: "};"))
        {
            if (overloads.Count == 1)
            {
                EmitSingleOverloadBody(sb, baseMethod, argOffset);
            }
            else
            {
                EmitOverloadResolutionBody(sb, overloads, argOffset);
            }
        }
    }

    /// <summary>Emits the body for a method with a single overload — strict argument reads via ReadArg* helpers.</summary>
    private void EmitSingleOverloadBody(IndentedStringBuilder sb, LuaMethodMetadata baseMethod, int argOffset)
    {
        if (!baseMethod.IsStatic && !baseMethod.IsInstanceConstructor)
        {
            sb.AppendLine($"var instance = ReadArg<{type.FullTypeName}>(state, args[0], 0);");
        }

        for (var i = 0; i < baseMethod.Parameters.Length; i++)
        {
            var p = baseMethod.Parameters[i];
            var t = p.Type;
            if (t == null)
            {
                sb.AppendLine($"#error {p.TypeName} is not INamedTypeSymbol");
            }
            else
            {
                sb.AppendLine($"var arg{i} = {ReadArgExpression($"args[{i + argOffset}]", t, i + argOffset)};");
            }
        }

        EmitCallAndReturn(sb, baseMethod, "arg");
    }

    /// <summary>
    /// Emits runtime overload resolution: disambiguate overloads by the provided argument count,
    /// probe each candidate's parameters in priority order with TryRead, and execute the first match.
    /// </summary>
    private void EmitOverloadResolutionBody(IndentedStringBuilder sb, IReadOnlyList<LuaMethodMetadata> overloads, int argOffset)
    {
        var baseMethod = overloads[0];
        if (!baseMethod.IsStatic && !baseMethod.IsInstanceConstructor)
        {
            sb.AppendLine($"var instance = ReadArg<{type.FullTypeName}>(state, args[0], 0);");
        }

        foreach (var group in overloads.GroupBy(m => m.Parameters.Length).OrderBy(g => g.Key))
        {
            var parameterCount = group.Key;
            sb.AppendLine($"if (args.Length == {argOffset + parameterCount})");
            using (sb.Block())
            {
                for (var i = 0; i < parameterCount; i++)
                {
                    sb.AppendLine($"var raw{i} = args[{argOffset + i}];");
                }

                foreach (var candidate in group)
                {
                    EmitOverloadCandidate(sb, candidate, parameterCount);
                }
            }
        }

        sb.AppendLine($"state.RaiseError($\"No overload of '{baseMethod.LuaName}' matches the provided arguments.\");");
        sb.AppendLine("return 0;");
    }

    /// <summary>Emits one overload-resolution candidate: a TryRead probe chain that executes the method body on full match.</summary>
    private void EmitOverloadCandidate(IndentedStringBuilder sb, LuaMethodMetadata candidate, int parameterCount)
    {
        var probes = new List<string>(parameterCount);
        var preDeclared = new List<string>();
        for (var i = 0; i < candidate.Parameters.Length; i++)
        {
            var p = candidate.Parameters[i];
            var t = p.Type;
            if (t == null)
            {
                sb.AppendLine($"#error {p.TypeName} is not INamedTypeSymbol");
                return;
            }

            if (t.IsReferenceType)
            {
                // nil converts to null for reference-type parameters.
                // Assign into a pre-declared variable so it is definitely assigned even when the
                // probe short-circuits on nil.
                preDeclared.Add($"{t.FullTypeName} a{i} = null!;");
                probes.Add($"(raw{i}.Type is global::NuLua.LuaValueType.Nil || raw{i}.TryRead<{t.FullTypeName}>(out a{i}))");
            }
            else if (t.IsNullableValueType)
            {
                probes.Add($"TryConvertNullable<{t.FullTypeName[..^1]}>(raw{i}, out var a{i})");
            }
            else
            {
                probes.Add($"raw{i}.TryRead<{t.FullTypeName}>(out var a{i})");
            }
        }

        if (probes.Count == 0)
        {
            using (sb.Block())
            {
                EmitCallAndReturn(sb, candidate, "a");
            }
            return;
        }

        // Nested block scopes the out-vars declared in the if condition to this candidate,
        // so sibling candidates in the same count block can reuse the same variable names.
        using (sb.Block())
        {
            foreach (var declaration in preDeclared)
            {
                sb.AppendLine(declaration);
            }

            sb.AppendLine($"if ({string.Join(" && ", probes)})");
            using (sb.Block())
            {
                EmitCallAndReturn(sb, candidate, "a");
            }
        }
    }

    /// <summary>Emits the call site and return marshalling for a resolved overload. Arg variables are named '{argPrefix}{i}'.</summary>
    private void EmitCallAndReturn(IndentedStringBuilder sb, LuaMethodMetadata method, string argPrefix)
    {
        if (!method.IsVoid || method.IsInstanceConstructor)
        {
            sb.Append("var result = ");
        }

        var argExpressions = string.Join(", ", Enumerable.Range(0, method.Parameters.Length).Select(i => $"{argPrefix}{i}"));
        if (method is LuaConstructorMetadata)
        {
            sb.AppendLine($"new {method.DeclaringType?.FullTypeName}({argExpressions});");
        }
        else if (method.IsStatic)
        {
            sb.AppendLine($"{method.DeclaringType?.FullTypeName}.{method.Name}({argExpressions});");
        }
        else
        {
            sb.AppendLine($"instance.{method.Name}({argExpressions});");
        }

        if (method.IsVoid && !method.IsInstanceConstructor)
        {
            sb.AppendLine("return 0;");
        }
        else
        {
            var returnType = method.IsInstanceConstructor ? type : method.ReturnType;
            if (returnType != null)
            {
                sb.AppendLine($"PushValue(state, {MarshalToLua("state", "result", returnType)});");
            }
            else
            {
                sb.AppendLine($"#error {method.ReturnTypeName} is not INamedTypeSymbol");
            }
            sb.AppendLine("return 1;");
        }
    }

    /// <summary>Emits a static property/field index handler for the type table's metatable.</summary>
    private void EmitStaticIndex(IndentedStringBuilder sb)
    {
        sb.AppendLine($"internal static readonly global::NuLua.LuaFunc<global::NuLua.Luau.LuauState> {GetStaticMetamethodName(type, Metamethods.Index)} = (state, args) =>");
        using (sb.Block(end: "};"))
        {
            sb.AppendLine("var key = args[1];");
            sb.AppendLine("if (key.TryRead<string>(out var stringKey))");
            using (sb.Block())
            {
                foreach (var field in type.StaticFields.Where(f => IsMarshallable(f.FieldType)))
                {
                    sb.AppendLine($"if (stringKey == \"{field.LuaName}\") {{ PushValue(state, {MarshalToLua("state", $"{type.FullTypeName}.{field.Name}", field.FieldType)}); return 1; }}");
                }
                foreach (var prop in type.StaticProperties.Where(p => p.HasGetter && IsMarshallable(p.PropertyType)))
                {
                    sb.AppendLine($"if (stringKey == \"{prop.LuaName}\") {{ PushValue(state, {MarshalToLua("state", $"{type.FullTypeName}.{prop.Name}", prop.PropertyType)}); return 1; }}");
                }
            }
            sb.AppendLine("state.PushNil();");
            sb.AppendLine("return 1;");
        }
    }

    /// <summary>Emits a static property/field newindex handler for the type table's metatable.</summary>
    private void EmitStaticNewIndex(IndentedStringBuilder sb)
    {
        sb.AppendLine($"internal static readonly global::NuLua.LuaFunc<global::NuLua.Luau.LuauState> {GetStaticMetamethodName(type, Metamethods.NewIndex)} = (state, args) =>");
        using (sb.Block(end: "};"))
        {
            sb.AppendLine("var key = args[1];");
            sb.AppendLine("var value = args[2];");
            sb.AppendLine("if (key.TryRead<string>(out var stringKey))");
            using (sb.Block())
            {
                foreach (var field in type.StaticFields.Where(f => !f.IsReadOnly && IsMarshallable(f.FieldType)))
                {
                    sb.AppendLine($"if (stringKey == \"{field.LuaName}\") {{ {type.FullTypeName}.{field.Name} = {ReadArgExpression("value", field.FieldType, 2)}; return 0; }}");
                }
                foreach (var prop in type.StaticProperties.Where(p => p.HasSetter && IsMarshallable(p.PropertyType)))
                {
                    sb.AppendLine($"if (stringKey == \"{prop.LuaName}\") {{ {type.FullTypeName}.{prop.Name} = {ReadArgExpression("value", prop.PropertyType, 2)}; return 0; }}");
                }
                sb.AppendLine($"state.RaiseError($\"'{{stringKey}}' not found or read-only.\");");
            }
            sb.AppendLine("return 0;");
        }
    }

    /// <summary>Produces an argument read expression for <paramref name="t"/> from <paramref name="valueExpr"/>.</summary>
    private string ReadArgExpression(string valueExpr, BaseLuaTypeMetadata t, int index)
    {
        var prefix = $"global::{ns}.GeneratorGenerated.";
        if (t.IsReferenceType)
            return $"{prefix}ReadArgRef<{t.FullTypeName}>(state, {valueExpr}, {index})";
        if (t.IsNullableValueType)
            return $"{prefix}ReadArgNullable<{t.FullTypeName[..^1]}>(state, {valueExpr}, {index})";
        return $"{prefix}ReadArg<{t.FullTypeName}>(state, {valueExpr}, {index})";
    }

    /// <summary>Emits the per-state type-table factory for a non-enum type.</summary>
    private void EmitTypeTableInit(IndentedStringBuilder sb)
    {
        sb.AppendLine($"internal static global::NuLua.LuaTable {GetInitMethodName(type)}(global::NuLua.Luau.LuauState state)");
        using (sb.Block())
        {
            sb.AppendLine($"var typeTable = state.CreateTable(0, {type.StaticMethods.Count(IsMethodBindable) + type.Constructors.Count(IsMethodBindable) + type.InstanceMethods.Count(IsMethodBindable)});");

            foreach (var method in type.StaticMethods.Where(IsMethodBindable))
            {
                sb.AppendLine($"typeTable[\"{method.LuaName}\"] = global::NuLua.LuaValue.FromFunction(state.CreateFunction({GetFunctionName(type, method)}));");
            }
            foreach (var ctor in type.Constructors.Where(IsMethodBindable))
            {
                sb.AppendLine($"typeTable[\"{ctor.LuaName}\"] = global::NuLua.LuaValue.FromFunction(state.CreateFunction({GetFunctionName(type, ctor)}));");
            }
            // lua convention: static type table gets instance methods taking self as first parameter
            // it's very rare that you'd use these, but tooling expects it to be there
            foreach (var method in type.InstanceMethods.Where(IsMethodBindable))
            {
                sb.AppendLine($"typeTable[\"{method.LuaName}\"] = global::NuLua.LuaValue.FromFunction(state.CreateFunction({GetFunctionName(type, method)}));");
            }

            if (type.HasStaticIndex || type.HasStaticNewIndex)
            {
                sb.AppendLine("var typeTable_metatable = state.CreateTable(0, 2);");
                if (type.HasStaticIndex)
                {
                    sb.AppendLine($"typeTable_metatable[\"{Metamethods.Index}\"] = global::NuLua.LuaValue.FromFunction(state.CreateFunction({GetStaticMetamethodName(type, Metamethods.Index)}));");
                }
                if (type.HasStaticNewIndex)
                {
                    sb.AppendLine($"typeTable_metatable[\"{Metamethods.NewIndex}\"] = global::NuLua.LuaValue.FromFunction(state.CreateFunction({GetStaticMetamethodName(type, Metamethods.NewIndex)}));");
                }
                sb.AppendLine("state.PushValue(typeTable.Reference);");
                sb.AppendLine("state.SetMetatable(-1, typeTable_metatable);");
                sb.AppendLine("state.Pop(1);");
            }

            sb.AppendLine("return typeTable;");
        }
    }

    /// <summary>Emits the per-state type-table factory for an enum (members created via CreateEnumUserData).</summary>
    private void EmitEnumTypeTable(IndentedStringBuilder sb)
    {
        sb.AppendLine($"internal static global::NuLua.LuaTable {GetInitMethodName(type)}(global::NuLua.Luau.LuauState state)");
        using (sb.Block())
        {
            sb.AppendLine($"var typeTable = state.CreateTable(0, {type.EnumMembers.Length});");
            foreach (var member in type.EnumMembers)
            {
                sb.AppendLine($"typeTable[\"{member.LuaName}\"] = global::NuLua.LuaValue.FromUserData(state.CreateEnumUserData({type.FullTypeName}.{member.Name}));");
            }
            sb.AppendLine("return typeTable;");
        }
    }


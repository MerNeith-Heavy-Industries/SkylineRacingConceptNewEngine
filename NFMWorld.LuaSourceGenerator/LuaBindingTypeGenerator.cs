    private void EmitTypePartial(IndentedStringBuilder sb)
    {
        sb.Append($"partial {(type.IsRecord ? "record " : "")}{(type.IsValueType ? "struct " : type.IsInterface ? "interface " : "class ")}{type.TypeName}");
        sb.Append($" : global::NuLua.ILuaUserData<{type.FullTypeName}>");
        sb.AppendLine();
        using (sb.Block())
        {
            EmitSupportedMetamethods(sb);
            EmitTryGetIndex(sb);
            EmitTrySetIndex(sb);
            EmitToLuaString(sb);
            if (!type.IsInterface)
            {
                EmitOperators(sb);
            }
        }
    }

    private void EmitSupportedMetamethods(IndentedStringBuilder sb)
    {
        sb.AppendLine("public static global::NuLua.LuaUserDataMetamethods SupportedMetamethods =>");
        using (sb.Indent())
        {
            var flags = new List<string>();
            if (type.HasIndex) flags.Add("global::NuLua.LuaUserDataMetamethods.Index");
            if (type.HasNewIndex) flags.Add("global::NuLua.LuaUserDataMetamethods.NewIndex");
            flags.Add("global::NuLua.LuaUserDataMetamethods.ToString");
            foreach (var op in type.Operators.Where(IsOperatorSupported))
            {
                if (OperatorMetamethodFlag(op.MetamethodName) is { } flag)
                    flags.Add($"global::NuLua.LuaUserDataMetamethods.{flag}");
            }

            for (var i = 0; i < flags.Count; i++)
            {
                sb.AppendLine($"{flags[i]}{(i == flags.Count - 1 ? ";" : "|")}");
            }
        }
    }

    private void EmitTryGetIndex(IndentedStringBuilder sb)
    {
        sb.AppendLine("public bool TryGetIndex(global::NuLua.Luau.LuauState state, global::NuLua.LuaValue key, out global::NuLua.LuaValue value)");
        using (sb.Block())
        {
            sb.AppendLine("if (key.TryRead<string>(out var stringKey))");
            using (sb.Block())
            {
                foreach (var field in type.InstanceFields.Where(f => IsMarshallable(f.FieldType)))
                {
                    sb.AppendLine($"if (stringKey == \"{field.LuaName}\") {{ value = {MarshalToLua("state", $"this.{field.Name}", field.FieldType)}; return true; }}");
                }
                foreach (var prop in type.InstanceProperties.Where(p => p.HasGetter && IsMarshallable(p.PropertyType)))
                {
                    sb.AppendLine($"if (stringKey == \"{prop.LuaName}\") {{ value = {MarshalToLua("state", $"this.{prop.Name}", prop.PropertyType)}; return true; }}");
                }
                foreach (var method in type.InstanceMethods.Where(IsMethodBindable))
                {
                    sb.AppendLine($"if (stringKey == \"{method.LuaName}\") {{ value = global::NuLua.LuaValue.FromFunction(state.CreateFunction(global::{ns}.GeneratorGenerated.{GetFunctionName(type, method)})); return true; }}");
                }
            }
            sb.AppendLine("value = default;");
            sb.AppendLine("return false;");
        }
    }

    private void EmitTrySetIndex(IndentedStringBuilder sb)
    {
        sb.AppendLine("public bool TrySetIndex(global::NuLua.Luau.LuauState state, global::NuLua.LuaValue key, global::NuLua.LuaValue value)");
        using (sb.Block())
        {
            sb.AppendLine("if (key.TryRead<string>(out var stringKey))");
            using (sb.Block())
            {
                foreach (var field in type.InstanceFields.Where(f => !f.IsReadOnly && IsMarshallable(f.FieldType)))
                {
                    sb.AppendLine($"if (stringKey == \"{field.LuaName}\") {{ this.{field.Name} = {ReadArgExpression("value", field.FieldType, 2)}; return true; }}");
                }
                foreach (var prop in type.InstanceProperties.Where(p => p.HasSetter && IsMarshallable(p.PropertyType)))
                {
                    sb.AppendLine($"if (stringKey == \"{prop.LuaName}\") {{ this.{prop.Name} = {ReadArgExpression("value", prop.PropertyType, 2)}; return true; }}");
                }
            }
            sb.AppendLine("return false;");
        }
    }

    private void EmitToLuaString(IndentedStringBuilder sb)

    // ================================================================
    // Operators (ILuaUserData<T> static virtual members)
    // ================================================================

    private void EmitOperators(IndentedStringBuilder sb)
    {
        foreach (var op in type.Operators.Where(IsOperatorSupported))
        {
            EmitOperator(sb, op);
        }
    }

    /// <summary>Only same-type operands are supported — the userdata metamethod bridge reads both as T.</summary>
    private bool IsOperatorSupported(LuaOperatorMetadata op)
    {
        if (op.IsUnary)
            return op.Parameters.Length == 1 && op.Parameters[0].Type.FullTypeName == type.FullTypeName;
        return op.Parameters.Length == 2
            && op.Parameters[0].Type.FullTypeName == type.FullTypeName
            && op.Parameters[1].Type.FullTypeName == type.FullTypeName;
    }

    private void EmitOperator(IndentedStringBuilder sb, LuaOperatorMetadata op)
    {
        var methodName = OperatorMethodName(op.MetamethodName);
        var isBoolReturn = OperatorIsBoolean(op.MetamethodName);
        var selfType = type.FullTypeName;

        sb.Append($"public static {(isBoolReturn ? "bool" : "global::NuLua.LuaValue")} {methodName}(global::NuLua.Luau.LuauState state, {selfType} self");
        if (!op.IsUnary)
        {
            sb.Append($", {selfType} other");
        }
        sb.AppendLine(")");
        using (sb.Block())
        {
            var expr = op.IsUnary ? $"{op.Operator}self" : $"self {op.Operator} other";
            if (isBoolReturn)
            {
                sb.AppendLine($"return {expr};");
            }
            else
            {
                sb.AppendLine($"var result = {expr};");
                sb.AppendLine($"return global::NuLua.LuaValue.FromUserData(state.CreateUserData(result));");
            }
        }
    }

    private static string OperatorMethodName(string metamethod) => metamethod switch
    {
        Metamethods.Add => "Add",
        Metamethods.Sub => "Subtract",
        Metamethods.Div => "Divide",
        Metamethods.Mod => "Modulus",
        Metamethods.Unm => "UnaryMinus",
        Metamethods.Eq => "Equals",
        Metamethods.Lt => "LessThan",
        Metamethods.Le => "LessThanOrEqual",
        _ => throw new ArgumentOutOfRangeException(nameof(metamethod), metamethod, "Unsupported operator metamethod")
    };

    private static bool OperatorIsBoolean(string metamethod) =>
        metamethod is Metamethods.Eq or Metamethods.Lt or Metamethods.Le;

    private static string? OperatorMetamethodFlag(string metamethod) => metamethod switch
    {
        Metamethods.Add => "Add",
        Metamethods.Sub => "Sub",
        Metamethods.Div => "Div",
        Metamethods.Mod => "Mod",
        Metamethods.Unm => "Unm",
        Metamethods.Eq => "Eq",
        Metamethods.Lt => "Lt",
        Metamethods.Le => "Le",
        _ => null
    };

    private static bool IsMethodBindable(LuaMethodMetadata m) =>
        IsMarshallable(m.ReturnType) && m.Parameters.All(p => IsMarshallable(p.Type));
}

